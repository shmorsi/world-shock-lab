"""docs/SIMULATION.md: Monte Carlo evidence that the estimators recover known responses."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from wsl.estimation import montecarlo as mc
from wsl.estimation.simulate import textbook_var
from wsl.paths import DOCS_DIR, ROOT

OUT = DOCS_DIR / "SIMULATION.md"


def _md(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        cells = ["—" if isinstance(v, float) and np.isnan(v)
                 else floatfmt.format(v) if isinstance(v, float) else str(v) for v in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def _matrix(m: np.ndarray) -> str:
    return "\n".join("    [" + ", ".join(f"{v:6.2f}" for v in row) + "]" for row in m)


def write(path: Path = OUT) -> Path:
    var = textbook_var()
    runs = [
        ("Monthly-like, Gaussian shock every period (T = 500)", [
            mc.dense("NW", outcome=1), mc.dense("HC1", outcome=1),
            mc.dense("NW", outcome=0), mc.dense("NW", outcome=2)]),
        ("Daily-like, sparse fat-tailed shock (~3% of days, t(4) sizes, T = 8000)", [
            mc.sparse("event_HC3"), mc.sparse("zerofill_NW"), mc.sparse("zerofill_HC1"),
            mc.sparse("zerofill_HC3")]),
        ("LP-IV with a noisy external instrument (T = 500)", [
            mc.lpiv(1.0), mc.lpiv(0.05)]),
        ("Placebo: independent sparse 'shock', true response zero (T = 8000)", [
            mc.placebo()]),
    ]
    small, large = mc.consistency()
    bv_rows = [mc.proxy_bvar_mc(lam=0.2), mc.proxy_bvar_mc(lam=1e4)]

    parts = [
        "# Simulation recovery of known impulse responses\n",
        "Generated by `uv run wsl validate simulation` (code: `wsl/estimation/montecarlo.py`). "
        "Do not edit by hand. The same seeded experiments are asserted in "
        "`tests/test_simulation_recovery.py`.\n",
        "## Data-generating process\n",
        "Structural VAR(2) with three variables (0 = policy rate, 1 = activity, 2 = prices), "
        "Y_t = A1 Y_{t-1} + A2 Y_{t-2} + B ε_t, with companion spectral radius "
        f"{var.companion_radius():.3f}. The responses estimated are those of variable 1 (and "
        "0 and 2 where shown) to shock 0, for h = 0..12.\n",
        "```\nA1 =\n" + _matrix(var.A[0]) + "\nA2 =\n" + _matrix(var.A[1]) + "\nB =\n"
        + _matrix(var.B) + "\n```\n",
        "Pass criteria (M2, docs/PLAN.md §6): |bias| ≤ 5% of the peak response + 4 Monte "
        "Carlo s.e. at every horizon; mean coverage of the 90% band in [0.85, 0.95], with no "
        "horizon below 0.80.\n",
    ]
    for title, results in runs:
        rows = []
        for r in results:
            s = r.summary()
            rows.append({"experiment": r.name, **{k: v for k, v in s.items() if k != "R"},
                         "draws": int(s["R"])})
        parts.append(f"## {title}\n")
        parts.append(_md(pd.DataFrame(rows)))
    parts.append("## Proxy BVAR (moving-block bootstrap)\n")
    parts.append(
        "BVAR with 4 lags on data from the VAR(2) above, identified with a noisy instrument "
        "(z = ε₀ + ν), 90% percentile bands from 200 bootstrap draws in each of 100 samples "
        "(T = 400). The first row uses the pre-registered prior tightness 0.2. The second "
        "row is effectively no prior, for comparison.\n")
    parts.append(_md(pd.DataFrame([{
        "prior tightness": "0.2 (pre-registered)" if r["lam"] == 0.2 else "none (OLS VAR)",
        "coverage 90, other variables": r["coverage90_other_variables"],
        "coverage 90, normalized variable's own path": r["coverage90_own_path"],
        "max |bias| / peak, other variables": r["max_abs_bias_other_over_peak"],
        "max |bias|, own path": r["max_abs_bias_own_path"],
        "median first-stage F": r["median_first_stage_f"]} for r in bv_rows])))
    parts.append("## Consistency\n")
    parts.append(f"RMSE of the dense LP (HC1) across all horizons: {small:.4f} at T = 250, "
                 f"{large:.4f} at T = 2000 (ratio {large / small:.2f}).\n")
    dense_runs, sparse_runs, iv_runs, placebo_runs = (r for _, r in runs)
    d_cov = [r.coverage90.mean() for r in dense_runs]
    ev, zf_nw, _, zf_hc3 = sparse_runs
    strong, weak = iv_runs
    parts.append(
        "## What this shows\n\n"
        f"- **LP with dense shocks:** Newey–West (h+1 lags) and lag-augmented HC errors both "
        f"give 90% bands with mean coverage between {min(d_cov):.2f} and {max(d_cov):.2f}, "
        "slightly below nominal, which is typical of finite samples. Relative bias is largest "
        "for the prices outcome only because its true peak response is small; in absolute "
        "terms it stays within a few Monte Carlo s.e.\n"
        f"- **Daily-like sparse, fat-tailed shocks:** the event-sample LP with HC3 errors, which "
        f"is the pre-registered primary daily specification (protocol §9), covers "
        f"{ev.coverage90.mean():.3f}. Time-series LPs with zero-filled shocks are unbiased but "
        f"their bands are too narrow ({zf_nw.coverage90.mean():.3f} with Newey–West). HC3 "
        f"narrows the gap ({zf_hc3.coverage90.mean():.3f}), which points to high-leverage event "
        "days. This is why zero-filled daily LPs are robustness checks only.\n"
        f"- **LP-IV, strong instrument** (median effective F "
        f"{strong.extra['median effective F']:.0f}): Wald bands cover "
        f"{strong.coverage90.mean():.3f}.\n"
        f"- **LP-IV, weak instrument** (median effective F "
        f"{weak.extra['median effective F']:.2f}): the point estimate is meaningless (mean bias "
        f"{np.max(np.abs(weak.bias)) / np.max(np.abs(weak.truth)):.0f} times the peak "
        f"response). Wald bands cover {weak.coverage90.mean():.3f} here only because they are "
        "enormous, so they carry no information. Anderson–Rubin sets keep coverage "
        f"{weak.extra['Anderson-Rubin coverage 90 (mean)']:.3f}. Every LP-IV result we report "
        "will therefore show the effective F and the Anderson–Rubin set.\n"
        f"- **Placebo:** an unrelated series produces responses indistinguishable from zero; "
        f"the 90% band contains zero in {placebo_runs[0].coverage90.mean():.3f} of draws.\n"
        f"- **Proxy BVAR:** percentile bootstrap bands are too narrow even without a prior "
        f"(coverage {bv_rows[1]['coverage90_other_variables']:.2f} for a nominal 0.90), as "
        "Kilian (1998) documents for persistent VARs. Shrinkage then biases the normalized "
        "variable's own path toward zero (coverage "
        f"{bv_rows[0]['coverage90_own_path']:.2f}). The responses we compare with LPs cover "
        f"{bv_rows[0]['coverage90_other_variables']:.2f}. This is the bias-variance trade-off: "
        "VAR bands are narrower than LP bands partly because they are too narrow, so wherever "
        "the two disagree the LP is the more trustworthy guide to uncertainty.\n"
    )
    path.write_text("\n".join(parts))
    return path.relative_to(ROOT)
