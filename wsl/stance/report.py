"""docs/STANCE.md and the README's stance block, generated from results/stance/. No hand-typed numbers."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from wsl.paths import ROOT
from wsl.stance.study import LABELS, RESULTS, protocol

DOC = ROOT / "docs" / "STANCE.md"
README = ROOT / "README.md"
START, END = "<!-- stance:start (generated by `uv run wsl stance report`; do not edit) -->", "<!-- stance:end -->"


def _load(name: str) -> dict[str, Any] | None:
    p = RESULTS / f"{name}.json"
    if not p.exists():
        return None
    data: dict[str, Any] = json.loads(p.read_text())
    return data


def _pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def readme_block(dev: dict[str, Any], test: dict[str, Any] | None, ext: dict[str, Any] | None) -> str:
    L = [START, "### Policy stance: a fine-tuned classifier of central-bank sentences", ""]
    lr = dev["lora_roberta"]
    L.append(f"`roberta-base` fine-tuned with **LoRA** adapters ({_pct(lr['parameters']['share'], 2)} of its parameters trained, on a CPU) to label "
             "FOMC sentences dovish, hawkish or neutral, against TF-IDF + logistic regression, on the labelled data of Shah, Paturi and Chava "
             "(ACL 2023). Protocol tagged `stance-v1` in git before any model was trained; the test split was scored once "
             "([docs/STANCE.md](docs/STANCE.md)).")
    L.append("")
    if test:
        p = test["primary"]
        L += ["| Model | Test macro-F1 | Accuracy |", "|---|---:|---:|",
              f"| Majority class | {test['majority']['macro_f1']:.3f} | {_pct(test['majority']['accuracy'])} |",
              f"| TF-IDF + logistic regression | {test['tfidf_logreg']['macro_f1']:.3f} | {_pct(test['tfidf_logreg']['accuracy'])} |",
              f"| **roberta-base + LoRA** | **{test['lora_roberta']['macro_f1']:.3f}** | {_pct(test['lora_roberta']['accuracy'])} |", "",
              f"LoRA minus TF-IDF: {p['difference']:+.3f} macro-F1 (90% CI {p['lo']:+.3f} to {p['hi']:+.3f}): **{p['verdict']}**."]
    if ext:
        s = ext["spearman"]
        L += ["", f"Out of domain, on {ext['pairs']} Bank of Canada statements: the classifier's stance and the next decision correlate at "
              f"{s['rho']:.2f} (90% CI {s['lo']:.2f} to {s['hi']:.2f}): {s['verdict']} (reduced form), though little of it survives "
              f"once today's decision is known (t {ext['ols']['t_stance']:.2f})."]
    L.append(END)
    return "\n".join(L)


def doc(dev: dict[str, Any], test: dict[str, Any] | None, ext: dict[str, Any] | None) -> str:
    pr = protocol()
    spec = pr["models"]["lora_roberta"]
    lr = dev["lora_roberta"]
    L = ["<!-- Generated by `uv run wsl stance report` from results/stance/; do not edit. -->", "# Policy stance", "",
         "**A LoRA fine-tuned transformer that reads central-bank sentences, against a bag-of-words baseline, with the test fixed in git first.**", "",
         "[Protocol](../config/stance_protocol.yaml) · [Code](../wsl/stance/) · [Results](../results/stance/)", "",
         "## The question", "", pr["question"].strip(), "",
         "## Data", "",
         f"`{pr['data']['source']}` at revision `{pr['data']['revision'][:12]}`: FOMC sentences (statements, minutes, speeches and press "
         f"conferences) labelled dovish, hawkish or neutral by Shah, Paturi and Chava, *Trillion Dollar Words* (ACL 2023), on the authors' "
         f"own train/test split. Licence {pr['data']['licence']}: downloaded on demand, never committed. Development: 20% of train, stratified, "
         f"seed 0 ({dev['n_train']} sentences train, {dev['n_dev']} develop).", "",
         "## Method, fixed before training", "",
         f"- **Baseline:** TF-IDF on word 1- and 2-grams, logistic regression with balanced class weights; C chosen on development ({dev['tfidf_logreg']['C']:g}).",
         f"- **LoRA:** `{spec['base']}` (revision `{spec['base_revision'][:12]}`), rank {spec['adapters']['r']}, alpha {spec['adapters']['alpha']}, "
         f"on the attention query and value projections, plus the classification head: {lr['parameters']['trainable']:,} of "
         f"{lr['parameters']['total']:,} parameters ({_pct(lr['parameters']['share'], 2)}). AdamW with linear decay, batch {spec['batch']}, "
         f"{spec['epochs']} epochs, the epoch with the best development macro-F1 kept. Learning rate chosen on development: {lr['learning_rate']:g} "
         f"(epoch {lr['epoch']}). Trained on four CPU threads.",
         "- **Primary comparison:** test macro-F1 of LoRA minus TF-IDF, paired bootstrap over sentences (10,000 draws), 90% interval. "
         "Helps if the interval is above zero, hurts if below, otherwise no detectable difference.",
         "- **Gate:** `wsl stance evaluate` refuses to score unless the `stance-v1` tag is in the commit's history with the protocol unchanged, "
         "and refuses a second scoring.", "",
         "## Development", "", "| Model | Dev macro-F1 | Accuracy |", "|---|---:|---:|",
         f"| Majority ({dev['majority']['label']}) | {dev['majority']['macro_f1']:.3f} | {_pct(dev['majority']['accuracy'])} |",
         f"| TF-IDF + logistic regression | {dev['tfidf_logreg']['macro_f1']:.3f} | {_pct(dev['tfidf_logreg']['accuracy'])} |",
         f"| roberta-base + LoRA | {lr['macro_f1']:.3f} | {_pct(lr['accuracy'])} |", "",
         "Learning curves (development macro-F1 by epoch):", ""]
    for k, run in lr["runs"].items():
        L.append(f"- learning rate {float(k):g}: " + ", ".join(f"{h['dev_macro_f1']:.3f}" for h in run["history"]) +
                 f" ({run['seconds'] / 60:.0f} min)")
    L.append("")
    if test:
        t = test
        p = t["primary"]
        L += ["## Test (scored once)", "", "| Model | Macro-F1 | Weighted F1 | Accuracy | F1 dovish | F1 hawkish | F1 neutral |", "|---|---:|---:|---:|---:|---:|---:|"]
        for key, name in (("majority", "Majority class"), ("tfidf_logreg", "TF-IDF + logistic regression"), ("lora_roberta", "roberta-base + LoRA")):
            m = t[key]
            L.append(f"| {name} | {m['macro_f1']:.3f} | {m['weighted_f1']:.3f} | {_pct(m['accuracy'])} | " +
                     " | ".join(f"{m['f1_by_class'][c]:.3f}" for c in LABELS) + " |")
        L += ["", f"**Primary comparison:** LoRA minus TF-IDF {p['difference']:+.3f} macro-F1, 90% CI {p['lo']:+.3f} to {p['hi']:+.3f}: **{p['verdict']}**.", "",
              f"Inference on CPU: {t['lora_cpu_ms_per_sentence']:.0f} ms a sentence (batch {spec['batch']}).", "",
              "Confusion matrix of the LoRA model (rows true, columns predicted; dovish, hawkish, neutral):", ""]
        L += ["| | dovish | hawkish | neutral |", "|---|---:|---:|---:|"]
        for name, row in zip(LABELS, t["lora_roberta"]["confusion"], strict=True):
            L.append(f"| {name} | " + " | ".join(str(v) for v in row) + " |")
        L.append("")
    if ext:
        s, o = ext["spearman"], ext["ols"]
        mb = ext["mean_stance_before"]
        L += ["## Out of domain: the Bank of Canada", "",
              f"{ext['statements_scored']} Bank of Canada statements, never seen in training, each scored without its first paragraph (which "
              f"announces the decision). {ext['pairs']} have a next scheduled decision ({ext['first']} to {ext['last']}).", "",
              f"- Spearman correlation of stance with the next decision's change: **{s['rho']:.2f}** (90% CI {s['lo']:.2f} to {s['hi']:.2f}): {s['verdict']}.",
              f"- Average stance before a hike {mb['hike']:+.2f}, before a hold {mb['hold']:+.2f}, before a cut {mb['cut']:+.2f}.",
              f"- With today's decision in the regression (HC1 errors): stance {o['coef_stance']:+.1f} bp per unit (t {o['t_stance']:.2f}), "
              f"today's change {o['coef_current']:+.2f} (t {o['t_current']:.2f}); R² {o['r2']:.2f}. Stance correlates with today's change at "
              f"{ext['spearman_with_current_change']:.2f}, so much of what it reads is the decision just taken.", "",
              "*Reduced form: a correlation between words and the next decision, not a causal estimate.*", ""]
    L += ["## Limits", "",
          "- One seed, one base model; the comparison is about this budget (a CPU, six epochs), not the best achievable score.",
          "- The labels are one team's reading; the authors report agreement between annotators, and their best model (RoBERTa-large, full fine-tuning) is the reference to compare against.",
          "- The Bank of Canada check uses a classifier trained on Fed language; a sentence-level label is a crude summary of a statement.", ""]
    return "\n".join(L)


def write() -> list[Path]:
    dev, test, ext = _load("dev"), _load("test"), _load("external")
    if dev is None:
        raise FileNotFoundError("results/stance/dev.json: run `wsl stance dev` first")
    DOC.write_text(doc(dev, test, ext))
    text = README.read_text()
    block = readme_block(dev, test, ext)
    if START in text:
        i, j = text.index(START), text.index(END) + len(END)
        text = text[:i] + block + text[j:]
    else:
        anchor = "Every output carries one of four labels"
        text = text.replace(anchor, block + "\n\n" + anchor, 1)
    README.write_text(text)
    return [DOC, README]
