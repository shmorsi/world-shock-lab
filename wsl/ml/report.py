"""docs/ML_BENCHMARK.md from results/ml/validation.json and the final run in results/final_eval/.
Every number is computed here."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd

from wsl.ml.evaluate import FINAL_DIR, RESULTS
from wsl.paths import DOCS_DIR, ROOT

OUT = DOCS_DIR / "ML_BENCHMARK.md"
LABELS = {"zero": "B0 zero forecast", "lp": "B1 unconditional LP", "state": "B2 state-dependent LP",
          "ridge": "B3 ridge", "gbm": "B4 gradient boosting", "mlp": "ML small MLP (5 seeds)"}


def _label(key: str) -> str:
    name = key.split(":")[0]
    extra = "" if ":" not in key else " " + ", ".join(
        f"{k}={v}" for k, v in json.loads(key.split(":", 1)[1]).items())
    return LABELS[name] + extra


def _md(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines) + "\n"


def _pooled(per_cell: dict[str, dict[str, float]], metric: str) -> float:
    vals = [c[metric] for c in per_cell.values() if c[metric] == c[metric]]
    return sum(vals) / len(vals)


def write(path: Path = OUT) -> Path:
    val = json.loads((RESULTS / "validation.json").read_text())
    finals = sorted(FINAL_DIR.glob("*.json"))
    parts = ["# ML benchmark: does machine learning add anything?\n",
             "Generated by `uv run wsl evaluate --report` from results/ml/validation.json and "
             "results/final_eval/. Do not edit by hand. Rules: docs/EVALUATION_PROTOCOL.md "
             "(splits, metrics and decision rule fixed before any model was fitted).\n"]
    if finals:
        fin: dict[str, Any] = json.loads(finals[-1].read_text())
        ci = fin["difference_ml_minus_econ"]["ci90"]
        parts.append(
            f"## Verdict: {fin['verdict']}\n\n"
            f"On {fin['test_events_primary']} held-out announcements from "
            f"{min(fin['test_years'])} to {max(fin['test_years'])}, the validation-selected ML "
            f"model ({_label(fin['candidates']['ml'])}) minus the validation-selected "
            f"econometric model ({_label(fin['candidates']['econometric'])}) has a pooled "
            f"scaled MAE difference of {fin['difference_ml_minus_econ']['point']:+.3f} (90% "
            f"event-block bootstrap CI [{ci[0]:+.3f}, {ci[1]:+.3f}]). Negative would favour ML. "
            f"Run {fin['generated_at']} at commit {fin['git_sha'][:12]}, protocol "
            f"{fin['protocol_tag']}; this is run number {len(finals)} on the test set.\n")
        rows = []
        for k, v in fin["pooled_scaled_mae"].items():
            pc = fin["per_cell"][k]
            rows.append({"model": _label(k), "pooled scaled MAE": f"{v:.3f}",
                         "OOS R² vs zero (mean)": f"{_pooled(pc, 'oos_r2_vs_zero'):+.3f}",
                         "directional accuracy": f"{_pooled(pc, 'directional_accuracy'):.2f}",
                         "coverage 68": f"{_pooled(pc, 'coverage68'):.2f}",
                         "coverage 90": f"{_pooled(pc, 'coverage90'):.2f}",
                         "interval score 90 (scaled)":
                             f"{_pooled(pc, 'interval_score90_scaled'):.2f}"})
        parts.append("## Test-set results (expanding annual refit, primary)\n\n"
                     "Scaled MAE divides each cell's MAE by the training-period MAE of the zero "
                     "forecast, so 1.00 = no better than predicting no move; averaged over 8 "
                     "assets × 2 horizons.\n\n" + _md(pd.DataFrame(rows)))
        cell_rows = []
        for cell in fin["per_cell"]["zero"]:
            r = {"cell": cell, "test N": int(fin["per_cell"]["zero"][cell]["n"])}
            for k in fin["pooled_scaled_mae"]:
                r[k.split(":")[0]] = f"{fin['per_cell'][k][cell]['scaled_mae']:.3f}"
            cell_rows.append(r)
        parts.append("### By asset and horizon (scaled MAE)\n\n" + _md(pd.DataFrame(cell_rows)))
        st = fin["static_refit"]
        parts.append(
            "## Secondary analyses (descriptive; cannot change the verdict)\n\n"
            f"- **Static refit** (models fit once on data up to 2018): difference "
            f"{st['difference_ml_minus_econ']['point']:+.3f}, CI "
            f"[{st['difference_ml_minus_econ']['ci90'][0]:+.3f}, "
            f"{st['difference_ml_minus_econ']['ci90'][1]:+.3f}]: {st['verdict']}.\n")
        sub_rows = [{"subsample": n, "events": s["events"],
                     **{k.split(":")[0]: f"{v:.3f}" for k, v in s["pooled_scaled_mae"].items()}}
                    for n, s in fin["subsamples"].items()]
        parts.append(_md(pd.DataFrame(sub_rows)))
        att = fin["attributions"]
        groups = sorted({g for v in att.values() for g in v})
        att_rows = [{"feature group": g, **{k.split(":")[0]: f"{att[k].get(g, float('nan')):+.3f}"
                                            for k in att}} for g in groups]
        parts.append("## What the models use (permutation importance)\n\n"
                     "Increase in pooled scaled MAE on the test events when a feature group is "
                     "shuffled (static models). Larger = more relied upon; near zero or "
                     "negative = not useful.\n\n" + _md(pd.DataFrame(att_rows)))
    else:
        parts.append("## Verdict: pending\n\nThe single final test run has not been made.\n")
    vrows = [{"model": _label(k), "validation pooled scaled MAE": f"{v:.3f}"}
             for k, v in sorted(val["pooled_scaled_mae"].items(), key=lambda kv: kv[1])]
    parts.append(
        "## Validation phase (model selection, 2015-2018)\n\n"
        f"Trained on {val['counts']['train']} announcements up to 2014, scored on "
        f"{val['counts']['validation']} from 2015-2018. Chosen: gradient boosting "
        f"{_label(val['chosen']['gbm'])}; MLP {_label(val['chosen']['mlp'])}. Candidates for the "
        f"test: econometric = {_label(val['candidates']['econometric'])}, ML = "
        f"{_label(val['candidates']['ml'])}.\n\n" + _md(pd.DataFrame(vrows)))
    path.write_text("\n".join(parts))
    return path.relative_to(ROOT)
