"""docs/RAG.md and the README's "Ask the decisions" block, generated from results/rag/.

Every number goes through ``Nums.f``, which records it; ``unregistered`` lists any number in
the text that did not (tests/test_rag.py fails on one), so none is typed by hand.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from wsl.paths import DOCS_DIR, ROOT
from wsl.rag.evaluate import RESULTS
from wsl.rag.text import protocol

RAG_DOC = DOCS_DIR / "RAG.md"
README = ROOT / "README.md"
START = "<!-- rag:start (generated by `uv run wsl rag report`; do not edit) -->"
END = "<!-- rag:end -->"
NUMBER = re.compile(r"[−+-]?\d+(?:,\d{3})*(?:\.\d+)?%?")
NAMES = {
    "bm25": "Keyword (BM25)",
    "static": "Static embeddings (`potion-base-8M`)",
    "transformer": "Transformer embeddings (`bge-small-en-v1.5`)",
    "hybrid_static": "Keyword + static, fused (the website)",
    "hybrid": "Keyword + transformer, fused",
}


class Nums:
    def __init__(self) -> None:
        self.seen: set[str] = set()

    def f(self, x: float | int | str, spec: str = "") -> str:
        if isinstance(x, str):
            out = x
        elif spec == "pct":
            out = f"{x * 100:.1f}%"
        elif spec == "pts":
            v = x * 100
            out = f"{'+' if v > 0 else '−' if v < 0 else ''}{abs(v):.1f}"
        else:
            out = format(x, spec)
        self.seen.update(NUMBER.findall(out))
        return out


def unregistered(text: str, nums: Nums) -> list[str]:
    body = re.sub(r"`[^`]*`", "", text)
    body = re.sub(r"\]\([^)]*\)", "]", body)  # link targets
    body = re.sub(r"(?m)^#+ .*$", "", body)
    body = re.sub(r"(?m)^\s*\d+\. ", "", body)
    body = re.sub(r"\b(BM25|int8|(hit|MRR)@\d+)\b", "", body)  # names, not numbers
    return [t for t in NUMBER.findall(body) if t not in nums.seen]


def _load() -> dict[str, Any]:
    return {s: json.loads((RESULTS / f"{s}.json").read_text()) for s in ("dev", "test")}


def _counts() -> dict[str, Any]:
    from wsl.rag.corpus import load

    docs = load()
    return {"n": len(docs), "boc": sum(d.bank == "boc" for d in docs),
            "fed": sum(d.bank == "fed" for d in docs),
            "first": min(d.date for d in docs), "last": max(d.date for d in docs),
            "boc_last": max(d.date for d in docs if d.bank == "boc")}


def readme_block(r: dict[str, Any], c: dict[str, Any], n: Nums) -> str:
    t = r["test"]
    s, p, site = t["summary"], t["primary"], t["site_vs_bm25"]
    return f"""{START}
### Ask the decisions: retrieval over {n.f(c['n'])} central-bank statements

Search every Fed and Bank of Canada policy statement since {n.f(c['first'][:4])} by question, [in the browser](https://shmorsi.github.io/shock-lab/#/ask) or with `uv run wsl rag ask`. Answers cite the statement and its official URL, and an answer that prints a number its sources do not contain is withheld. The retrievers, {n.f(t['n_questions'])} test questions and the decision rule were tagged `rag-v1` in git before any retriever was written; the test was scored once ([docs/RAG.md](docs/RAG.md)).

| Retriever | Right statement in top {n.f(5)} (test) | Detail |
|---|---:|---|
| Keyword (BM25) | {n.f(s['bm25']['hit@5'], 'pct')} | baseline |
| Keyword + transformer embeddings, fused | **{n.f(s['hybrid']['hit@5'], 'pct')}** | {n.f(p['difference'], 'pts')} points, {n.f('90%')} CI {n.f(p['lo'], 'pts')} to {n.f(p['hi'], 'pts')}: **{p['verdict']}** |
| Keyword + static embeddings, fused (runs in the browser) | {n.f(s['hybrid_static']['hit@5'], 'pct')} | {n.f(site['difference'], 'pts')} points, {n.f('90%')} CI {n.f(site['lo'], 'pts')} to {n.f(site['hi'], 'pts')}: {site['verdict']} |
{END}"""


def rag_doc(r: dict[str, Any], c: dict[str, Any], n: Nums) -> str:
    t, d = r["test"], r["dev"]
    p, site = t["primary"], t["site_vs_bm25"]
    proto = protocol()
    rows = "\n".join(
        f"| {NAMES[k]} | {n.f(t['summary'][k]['hit@1'], 'pct')} | "
        f"{n.f(t['summary'][k]['hit@5'], 'pct')} | {n.f(t['summary'][k]['hit@10'], 'pct')} | "
        f"{n.f(t['summary'][k]['mrr@10'], '.3f')} | {n.f(d['summary'][k]['hit@5'], 'pct')} |"
        for k in NAMES)
    fusion = proto["retrievers"]["fusion"]
    return f"""<!-- Generated by `uv run wsl rag report` from results/rag/; do not edit. -->
# Ask the decisions

**Retrieval-augmented answers from every Fed and Bank of Canada policy statement since {n.f(c['first'][:4])}, with a test fixed in git before the search was written.**

[Try it in the browser](https://shmorsi.github.io/shock-lab/#/ask) · [Protocol](../config/rag_protocol.yaml) · [Questions](../config/rag_questions.yaml) · [Code](../wsl/rag/) · [Browser twin](../web/src/ask/)

## The question

A reader asks "when did the Bank of Canada first say it would pause?" and wants the statement, not a guess. Does adding embedding search to keyword search find the right statement more often, for questions asked the way a reader would ask them?

## The corpus

{n.f(c['n'])} statements: {n.f(c['boc'])} Bank of Canada rate announcements (every row of `data/events/boc_fad.csv`, the lab's own announcement list) and {n.f(c['fed'])} FOMC statements, from {n.f(c['first'])} to {n.f(c['last'])}. Each page is downloaded through the lab's hashed raw cache (`data/manifest_rag.json`); the extracted paragraphs, the official URL and a hash of the text are committed in `data/rag/statements.jsonl`. Statements are split into paragraphs; a short paragraph joins the next, and every chunk starts with the bank, date and title, so a question that names a month and year can match.

## The method, fixed before the test

Five retrievers, compared on statement rank (a statement ranks where its best paragraph does):

- **Keyword:** BM25 with the protocol's tokenizer (stopwords, the S-stemmer).
- **Static embeddings:** `minishlab/potion-base-8M`, a vector per word piece averaged. Small enough to run in a browser.
- **Transformer embeddings:** `BAAI/bge-small-en-v1.5` through sentence-transformers, with the chunk vectors in a **Qdrant** collection (local mode; the same calls work against a Qdrant server).
- **Two hybrids:** keyword fused with each embedding by reciprocal rank fusion (k = {n.f(fusion['k'])}, the top {n.f(fusion['depth'])} chunks of each).

The {n.f(t['n_questions'])} test questions (half Fed, half Bank of Canada) and {n.f(d['n_questions'])} development questions were written with their answers by reading the statements, then tagged `rag-v1` with the protocol and the corpus. `wsl rag evaluate --split test` refuses to run on a commit without that tag in its history, or if the protocol, questions or corpus differ from it, and refuses a second scoring unless a reason is logged. Nothing was tuned: the development questions were used only to build the pipeline.

**Primary comparison:** keyword + transformer minus keyword, share of questions with a right statement in the top five, with a paired bootstrap interval over questions. The rule: it helps if the {n.f('90%')} interval is above zero, hurts if below, otherwise no detectable difference.

## Results

**Keyword + transformer finds a right statement in the top five for {n.f(t['summary']['hybrid']['hit@5'], 'pct')} of the test questions; keyword alone {n.f(t['summary']['bm25']['hit@5'], 'pct')}. Difference {n.f(p['difference'], 'pts')} points, {n.f('90%')} CI {n.f(p['lo'], 'pts')} to {n.f(p['hi'], 'pts')}: {p['verdict']}.** The browser's hybrid (keyword + static) scores {n.f(t['summary']['hybrid_static']['hit@5'], 'pct')}, {n.f(site['difference'], 'pts')} points over keyword ({n.f('90%')} CI {n.f(site['lo'], 'pts')} to {n.f(site['hi'], 'pts')}): {site['verdict']}.

| Retriever | Test hit@1 | Test hit@5 | Test hit@10 | Test MRR@10 | Dev hit@5 |
|---|---:|---:|---:|---:|---:|
{rows}

hit@k: share of questions with a right statement among the top k. MRR@10: mean of one over the rank of the first right statement (zero beyond rank {n.f(10)}). Test: {n.f(t['n_questions'])} questions; dev: {n.f(d['n_questions'])}.

**Reading the result.** The transformer is what lifts the hybrid: on its own it ties keyword search at five but ranks the right statement first more often, and the two make different mistakes, so fusing them helps. The static model is weaker on its own and adds little to keyword search; it is on the website because it runs in a browser with no server. With {n.f(t['n_questions'])} questions only a large difference can be detected, and the test questions turned out harder than the development ones.

**Where it fails.** Most misses ask for the first time something happened ("the first cut after the {n.f('2022 to 2023')} hiking cycle"). Search finds statements about cuts, not the first one: that needs reasoning over dates, which an answering model or a date filter would add. Others use different words from the statement ("a full percentage point" against "100 basis points"). Fed statements repeat their wording from meeting to meeting, so a question that does not name a date often lands on a neighbouring meeting.

## Answers

`uv run wsl rag ask "..."` retrieves the top five statements and, with Anthropic credentials, asks Claude (`claude-opus-5-5`, server-side refusal fallbacks on) to answer only from those passages, citing them as `[1]` to `[5]`. The lab's market data for a cited announcement (first observation after it: {n.f('US 2-year')} yield, CAD per USD, WTI) is passed with it. Two checks run on every answer: it must cite a passage, and every digit run in it must appear in a cited passage or that market data. An answer that fails is withheld and the passages are shown instead. Without credentials, or if the model declines, the answer is the sentence of the best passage that shares the rarest words with the question. Generated answers are not scored here; that needs a model key and its own protocol tag.

The search is also a LangChain retriever (`wsl.rag.lc.StatementRetriever`), returning each statement's best paragraph as a `Document` with the bank, date, title and URL in its metadata.

## In the browser

[{n.f('View 9')} of the lab](https://shmorsi.github.io/shock-lab/#/ask) runs keyword search, and once the static model has loaded, the keyword + static hybrid, entirely in the browser. `web/src/ask/` is a TypeScript twin of the Python: `tests/fixtures/rag_cases.json` holds tokenizer, BM25, fusion and embedding cases both must reproduce, and `web/src/ask/ask.test.ts` checks the browser's rankings against Python's on all {n.f(t['n_questions'] + d['n_questions'])} questions (the browser stores vectors as int8, so near-ties may swap). The view can limit results to one bank; the scores above use no filter.

## Limits

- Questions and labels were written by an AI assistant reading the statements, which may favour keyword search; the rule was to avoid each answer's distinctive words.
- One labeller, no second check of the labels.
- The Bank of Canada statements end on {n.f(c['boc_last'])}, where the lab's announcement list ends; later decisions join when that list is rebuilt.
- Market data exists only for announcements in the lab's held-out replay period, and shows what moved that day, not what the statement caused.

## Reproduce

```bash
uv run wsl rag corpus            # statements from the pinned cache (add --refresh to re-download)
uv run wsl rag evaluate          # dev questions; --split test is scored once, after rag-v1
uv run wsl rag export            # the browser's files in web/public/data/ask*
uv run wsl rag ask "When did the Fed begin tapering its bond purchases?" --bank fed
uv run wsl rag report            # this document and the README block
```
"""


def render() -> tuple[dict[Path, str], Nums]:
    r, c, n = _load(), _counts(), Nums()
    block = readme_block(r, c, n)
    doc = rag_doc(r, c, n)
    readme = README.read_text()
    if START in readme:
        head, rest = readme.split(START, 1)
        readme = head + block + rest.split(END, 1)[1]
    else:
        anchor = "<!-- top:end -->"
        readme = readme.replace(anchor, anchor + "\n\n" + block, 1)
    return {RAG_DOC: doc, README: readme}, n


def write() -> list[Path]:
    out, _ = render()
    for path, text in out.items():
        path.write_text(text)
    return list(out)
